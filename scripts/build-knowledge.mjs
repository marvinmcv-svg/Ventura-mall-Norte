// Builds Marvin's knowledge base (api/_knowledge.js) from the site's verified
// data (src/data.js) and the real posts saved in src/media.json: each
// restaurant's dishes, prices and promos, each store's promos at Ventura.
// Runs before every build; the output is committed too.
//   node scripts/build-knowledge.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mall, categories, stores, restaurants, events, legalPages } from '../src/data.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const M = JSON.parse(readFileSync(path.join(root, 'src/media.json'), 'utf8'));
const catName = Object.fromEntries(categories.map((c) => [c.id, c.name]));

const clean = (t = '', max = 600) => {
  const s = t.replace(/#\S+/g, '').replace(/[ \t]+/g, ' ').replace(/\n{2,}/g, '\n').trim();
  return s.length > max ? s.slice(0, max).replace(/\s+\S*$/, '') + '…' : s;
};
const postsOf = (codes, max, len) =>
  (codes || []).map((c) => ({ code: c, ...M.posts[c] })).filter((p) => p.caption).slice(0, max)
    .map((p) => `  - [${p.date}] ${clean(p.caption, len).replace(/\n/g, ' / ')}`);

const out = [];
out.push(`# VENTURA MALL (Ventura Norte)
Lema: "${mall.tagline}" ${mall.hashtag}
Dirección: ${mall.address}, ${mall.city}. Coordenadas: ${mall.coords.lat}, ${mall.coords.lng}.
Teléfono: ${mall.phone} · Email: ${mall.email} · WhatsApp del Boulevard: +${mall.whatsapp.number}
Redes: Instagram ${mall.socials.instagram.handle}, TikTok ${mall.socials.tiktok.handle}, Facebook ${mall.socials.facebook.handle}
Horarios generales:
${mall.hours.map((h) => `- ${h.label}: ${h.value}`).join('\n')}
Datos: 110.000 m² construidos; 13 salas de cine, entre ellas una sala IMAX de 16 × 21 m y cuatro salas VIP; 4 plantas y un subsuelo; inaugurado el 30 de enero de 2014.
Ventura Sur es el nuevo mall del grupo: ya abrió al público y su inauguración oficial es el 28 de noviembre de 2026.
Páginas del sitio: / (inicio), /tiendas (directorio, filtros ?cat=moda|belleza|ninos|gastronomia|servicios), /tiendas/<tienda>, /boulevard, /boulevard/<restaurante>, ${legalPages.map((l) => `/legal/${l.slug} (${l.title})`).join(', ')}.`);

out.push(`\n# RUTA BOULEVARD (música en vivo, ejemplos recientes)\n${events.map((e) => `- ${e.title}: ${e.when}, ${e.where}. ${e.text}`).join('\n')}`);

out.push('\n# RESTAURANTES Y BARES DEL BOULEVARD');
for (const r of restaurants) {
  const posts = postsOf(M.accounts[r.ig]?.posts, 10, 520);
  out.push(`\n## ${r.name} — ${r.cuisine}
Página: /boulevard/${r.slug}${r.ig ? ` · Instagram @${r.ig}` : ''}
Horario: ${r.hours || mall.hours[2].value}
Reservas: ${[r.wa && `WhatsApp ${r.wa}`, r.phone && `teléfono ${r.phone}`].filter(Boolean).join(' · ') || 'en el local'}
Sobre el lugar: ${r.about}
Para probar: ${(r.menu || []).join(', ')}
${posts.length ? `Publicaciones recientes del local (platos, precios y promos; la fecha indica cuándo se publicó):\n${posts.join('\n')}` : ''}`);
  const mallPosts = postsOf(r.posts, 3, 520);
  if (mallPosts.length) out.push(`Publicaciones de @venturamalloficial sobre ${r.name}:\n${mallPosts.join('\n')}`);
}

out.push('\n# TIENDAS');
for (const s of stores) {
  const promos = postsOf(s.posts, 4, 420);
  out.push(`\n## ${s.name} — ${catName[s.cat]}
Página: /tiendas/${s.slug}${s.ig ? ` · Instagram @${s.ig}` : ''}
Ubicación: ${s.where ? `${s.where}, ` : ''}Ventura Mall
Horario: ${s.cat === 'servicios' ? mall.hours[3].value : mall.hours[0].value}
${[s.whatsapp && `WhatsApp: +${s.whatsapp}`, s.catalog && `Catálogo por WhatsApp: ${s.catalog}`].filter(Boolean).join(' · ')}
Sobre la marca: ${s.about}
Qué encontrás: ${(s.lines || []).join(', ')}
${promos.length ? `Novedades en Ventura (publicadas por @venturamalloficial):\n${promos.join('\n')}` : ''}`);
}

const text = out.join('\n').replace(/\n{3,}/g, '\n\n');
writeFileSync(path.join(root, 'api/_knowledge.js'),
  `// Generated by scripts/build-knowledge.mjs — do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(text)};\n`);
console.log(`knowledge: ${text.length} chars (~${Math.round(text.length / 3.6)} tokens)`);
